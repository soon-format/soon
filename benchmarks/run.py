#!/usr/bin/env python3
"""Token-efficiency benchmark: SOON vs JSON / YAML / TOON, simple to hard.

Usage (from repo root):
    PYTHONPATH=python/src python3 benchmarks/run.py [--tokenizer o200k_base]

- Sizes are measured in characters by default. Pass --tokenizer to measure
  real tokens with tiktoken (requires network access on first run to fetch
  the BPE file).
- TOON is encoded with the `toon-py` package (community port of the official
  @byjohann/toon TypeScript implementation); the column is skipped if the
  package is missing.
- Every SOON encoding is verified lossless (decode(encode(x)) == x) and
  never larger than compact JSON before being reported.

Writes benchmarks/results.json and benchmarks/results.md.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Callable

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python" / "src"))
sys.path.insert(0, str(ROOT / "benchmarks"))

from datasets import DATASETS  # noqa: E402

from soon_format import decode as soon_decode  # noqa: E402
from soon_format import encode as soon_encode  # noqa: E402


def formatters(tokenizer: str | None) -> dict[str, Callable[[Any], str]]:
    fmts: dict[str, Callable[[Any], str]] = {
        "json": lambda d: json.dumps(d, separators=(",", ":"), ensure_ascii=False),
        "json-pretty": lambda d: json.dumps(d, indent=2, ensure_ascii=False),
    }
    try:
        import yaml

        fmts["yaml"] = lambda d: yaml.safe_dump(
            d, default_flow_style=False, allow_unicode=True, sort_keys=False
        )
    except ImportError:
        print("note: pyyaml not installed; skipping YAML column", file=sys.stderr)
    try:
        from toon_py import encode as toon_encode

        fmts["toon"] = lambda d: toon_encode(d)
    except ImportError:
        print("note: toon-py not installed; skipping TOON column", file=sys.stderr)
    # SOON's auto-mode decisions use the same tokenizer the bench measures with.
    fmts["soon"] = lambda d: soon_encode(d, tokenizer=tokenizer)
    return fmts


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tokenizer", help="tiktoken encoding name (e.g. o200k_base)")
    args = parser.parse_args()

    counter: Callable[[str], int]
    unit = "chars"
    if args.tokenizer:
        import tiktoken

        enc = tiktoken.get_encoding(args.tokenizer)
        counter = lambda s: len(enc.encode(s))  # noqa: E731
        unit = f"tokens ({args.tokenizer})"
    else:
        counter = len

    fmts = formatters(args.tokenizer)
    results = []
    for name, desc, gen in DATASETS:
        data = gen()
        # Correctness gates for SOON before it may be reported.
        soon_doc = soon_encode(data, tokenizer=args.tokenizer)
        assert soon_decode(soon_doc) == data, f"lossless check failed: {name}"
        cj = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
        assert counter(soon_doc) <= counter(cj), f"never-worse check failed: {name}"

        sizes = {fmt: counter(f(data)) for fmt, f in fmts.items()}
        results.append({"dataset": name, "description": desc, "sizes": sizes})

    out = {"unit": unit, "results": results}
    (ROOT / "benchmarks" / "results.json").write_text(
        json.dumps(out, indent=2) + "\n", encoding="utf-8"
    )

    # Markdown table: savings vs compact JSON (positive = smaller).
    names = [f for f in fmts if f != "json"]
    lines = [
        f"# Size benchmark ({unit})",
        "",
        "Savings vs compact JSON; positive is smaller. Generated by `benchmarks/run.py`.",
        "",
        "| Dataset | json | " + " | ".join(names) + " |",
        "|---|---|" + "---|" * len(names),
    ]
    for r in results:
        base = r["sizes"]["json"]
        cells = []
        for fmt in names:
            n = r["sizes"].get(fmt)
            cells.append(f"{n} ({(1 - n / base) * 100:+.1f}%)" if n else "-")
        lines.append(f"| {r['dataset']} — {r['description']} | {base} | " + " | ".join(cells) + " |")
    md = "\n".join(lines) + "\n"
    (ROOT / "benchmarks" / "results.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
